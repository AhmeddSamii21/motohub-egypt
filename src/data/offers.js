/**
 * مركز العروض — مصدر بيانات العروض المُتحقَّق منها فقط.
 *
 * قاعدة صارمة: لا يوجد في المشروع أي بيانات عروض/خصومات موثوقة (تم فحص المصادر:
 * الكتالوج المُجمَّد، بيانات الأسعار المولَّدة، دفتر العمل المُزامَن). فلا يُختلق
 * خصم ولا عرض محدود الوقت ولا سعر ترويجي هنا إطلاقًا.
 *
 * - يُلاحظ أن دفتر العمل يحتوي على تحديثات أسعار (أسعار أقدم في الكتالوج المُجمَّد مقابل
 *   أسعار أحدث مولَّدة) — لكن «تغيّر سعر» ليس «عرض/خصم»: توجد صفحة تحديثات الأسعار
 *   المخصصة لذلك (#updates)، ولا يُستنتج منها أي خصم هنا.
 * - بنية VERIFIED_OFFERS جاهزة لعروض مستقبلية يوثّقها المالك بنفسه (كل حقولها مطلوبة
 *   عند الإضافة — لا يُقبل عرض ناقص الحقول). حالتها الآن فارغة ⇒ الواجهة تعرض حالة
 *   فراغ صادقة توضح أنه لا توجد عروض منشورة مُؤكَّدة حاليًا.
 */

/**
 * العروض المُتحقَّق منها — فارغة عمدًا (لا عرض موثوق بعد).
 * شكل العرض المستقبلي المطلوب (كل الحقول إلزامية، بلا تخمين):
 * { id, brand, name,          // ماركة واسم موديل موجودين في الكتالوج المُجمَّد
 *   details,                  // نص العرض المُؤكَّد كما وثّقه المالك
 *   validFrom?: 'YYYY-MM-DD', // فقط إن وُثّق تاريخ بدء فعلي
 *   validUntil?: 'YYYY-MM-DD',// فقط إن وُثّق تاريخ انتهاء فعلي
 *   terms?: string }          // فقط إن وُجدت شروط رسمية
 */
export const VERIFIED_OFFERS = Object.freeze([])

/** هل مركز العروض فارغ؟ (لتحديد حالة الفراغ في الواجهة) */
export function hasVerifiedOffers() {
  return VERIFIED_OFFERS.length > 0
}
