/** تصنيفات الأسئلة بترتيب ثابت — لعرض التبويبات بالترتيب الأصلي ذاته */
export const FAQ_CATEGORIES = [...new Set(FAQS.map((f) => f.category))]

/** بحث الأسئلة: تطبيع عربي معاد + مطابقة في السؤال والإجابة. الاستعلام الفارغ يعيد الكل */
export function searchFaqs(query) {
  const trimmed = typeof query === 'string' ? query.trim() : ''
  if (!trimmed) return FAQS
  return FAQS.filter((f) => searchMatches(f.q, trimmed) || searchMatches(f.a, trimmed))
}

/** أسئلة تصنيف واحد بترتيبها الأصلي — لا يُخترع تصنيف غير موجود */
export function faqsByCategory(category) {
  return FAQS.filter((f) => f.category === category)
}
